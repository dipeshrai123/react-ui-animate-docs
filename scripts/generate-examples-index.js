const fs = require('fs');
const path = require('path');

const BASE_INPUT_DIR = path.join(__dirname, '../src/examples');
const OUTPUT_FILE = path.join(__dirname, '../src/examples/index.ts');

/**
 * Escape template literal string for use in TypeScript
 */
function escapeTemplateLiteral(str) {
  return str
    .replace(/\\/g, '\\\\')  // Escape backslashes
    .replace(/`/g, '\\`')     // Escape backticks
    .replace(/\${/g, '\\${'); // Escape template expressions
}

/**
 * Recursively walk directory and collect all .tsx files with their content
 * Also collects matching .css files
 */
function walkDir(dir, baseDir, fileMap = {}, cssMap = {}) {
  const entries = fs.readdirSync(dir);
  
  entries.forEach((entry) => {
    const fullPath = path.join(dir, entry);
    const stat = fs.statSync(fullPath);
    
    if (stat.isDirectory()) {
      walkDir(fullPath, baseDir, fileMap, cssMap);
    } else if (entry.endsWith('.tsx')) {
      const relativePath = path.relative(baseDir, fullPath);
      const key = relativePath
        .replace(/\.tsx$/, '')
        .replace(/[\/\\]/g, '_')
        .replace(/\./g, '_')  // Replace dots with underscores
        .replace(/-/g, '_')
        .replace(/[^a-zA-Z0-9_]/g, '_'); // Replace any other non-alphanumeric chars
      
      // Read the file content
      const content = fs.readFileSync(fullPath, 'utf-8');
      fileMap[key] = {
        path: relativePath.replace(/\\/g, '/'),
        content: content,
      };
      
      // Check for matching CSS file
      const cssPath = fullPath.replace(/\.tsx$/, '.css');
      if (fs.existsSync(cssPath)) {
        const cssContent = fs.readFileSync(cssPath, 'utf-8');
        cssMap[key] = cssContent;
      }
    }
  });
  
  return { fileMap, cssMap };
}

/**
 * Generate TypeScript index file with all examples as string constants
 */
function generateIndex() {
  console.log('📦 Generating examples index...');
  
  const fileMap = {};
  const cssMap = {};
  const versionFolders = fs.readdirSync(BASE_INPUT_DIR).filter((entry) => {
    const fullPath = path.join(BASE_INPUT_DIR, entry);
    return fs.statSync(fullPath).isDirectory();
  });
  
  versionFolders.forEach((versionFolder) => {
    const versionPath = path.join(BASE_INPUT_DIR, versionFolder);
    const result = walkDir(versionPath, BASE_INPUT_DIR, fileMap, cssMap);
    Object.assign(fileMap, result.fileMap);
    Object.assign(cssMap, result.cssMap);
  });
  
  // Generate the index file with all examples as exported constants
  const exports = Object.entries(fileMap)
    .map(([key, { content }]) => {
      const escapedContent = escapeTemplateLiteral(content);
      return `export const ${key} = \`${escapedContent}\`;`;
    })
    .join('\n\n');
  
  // Generate CSS exports
  const cssExports = Object.entries(cssMap)
    .map(([key, content]) => {
      const escapedContent = escapeTemplateLiteral(content);
      return `export const ${key}_CSS = \`${escapedContent}\`;`;
    })
    .join('\n\n');
  
  // Read shared styles.css if it exists
  const sharedStylesPath = path.join(BASE_INPUT_DIR, 'styles.css');
  let sharedStylesExport = '';
  if (fs.existsSync(sharedStylesPath)) {
    const sharedStylesContent = fs.readFileSync(sharedStylesPath, 'utf-8');
    const escapedContent = escapeTemplateLiteral(sharedStylesContent);
    sharedStylesExport = `\nexport const sharedStyles = \`${escapedContent}\`;`;
  }
  
  const content = `// This file is auto-generated by scripts/generate-examples-index.js
// Do not edit this file manually
// Run "npm run generate:examples" to regenerate

${exports}

${cssExports ? `\n// CSS files\n${cssExports}` : ''}${sharedStylesExport}
`;
  
  fs.writeFileSync(OUTPUT_FILE, content, 'utf-8');
  console.log(`✅ Generated index with ${Object.keys(fileMap).length} examples`);
  if (Object.keys(cssMap).length > 0) {
    console.log(`   Including ${Object.keys(cssMap).length} CSS file(s)`);
  }
  console.log(`📄 Output: ${path.relative(process.cwd(), OUTPUT_FILE)}`);
}

generateIndex();

